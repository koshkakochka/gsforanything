// Regenerates worker/prompts.js from the prompt template literals in
// site-source/server.js, so the Worker and the Vercel server use identical
// prompts. Run before every Worker deploy: node worker/gen-prompts.mjs
import fs from 'fs';
const here = new URL('.', import.meta.url);
const src = fs.readFileSync(new URL('../site-source/server.js', here), 'utf8');
const get = (name) => {
  const start = src.indexOf(`const ${name} = \``);
  if (start < 0) throw new Error(`${name} not found in server.js`);
  let i = start + `const ${name} = \``.length;
  for (; i < src.length; i++) { if (src[i] === '\\') { i++; continue; } if (src[i] === '`') break; }
  const lit = src.slice(start + `const ${name} = `.length, i + 1);
  return new Function(`return ${lit};`)();
};
const names = ['SYSTEM_PROMPT', 'FIX_CODE_PROMPT', 'THEME_SYSTEM_PROMPT'];
const out = '// Generated by worker/gen-prompts.mjs from site-source/server.js. Do not edit.\n'
  + names.map((n) => `export const ${n} = ${JSON.stringify(get(n))};`).join('\n\n') + '\n';
fs.writeFileSync(new URL('prompts.js', here), out);
console.log('worker/prompts.js written', names.map((n) => `${n}=${get(n).length}`).join(' '));
